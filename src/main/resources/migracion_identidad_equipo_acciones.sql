-- Migración única desde el esquema anterior (equipo.codigo como PK).
-- Aplicar en una transacción y con respaldo previo; no ejecutarla en producción
-- sin una ventana y un plan de reversión aprobados.
BEGIN;

ALTER TABLE equipo
    ADD COLUMN id_equipo BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN activo BOOLEAN NOT NULL DEFAULT TRUE;

DO $$
BEGIN
    IF to_regclass('public.registro_carbono') IS NOT NULL THEN
        EXECUTE 'ALTER TABLE registro_carbono DROP CONSTRAINT fk_registro_carbono_equipo';
    END IF;
END $$;

-- Las claves foraneas dependen de la PK antigua (codigo); se eliminan antes de cambiarla.
ALTER TABLE orden_mantenimiento DROP CONSTRAINT fk_orden_equipo;

ALTER TABLE equipo ALTER COLUMN codigo SET NOT NULL;
ALTER TABLE equipo DROP CONSTRAINT pk_equipo;
ALTER TABLE equipo ADD CONSTRAINT pk_equipo PRIMARY KEY (id_equipo);
ALTER TABLE equipo ADD CONSTRAINT uq_equipo_codigo UNIQUE (codigo);
ALTER TABLE equipo ADD CONSTRAINT uq_equipo_id_codigo UNIQUE (id_equipo, codigo);

ALTER TABLE orden_mantenimiento ADD COLUMN id_equipo BIGINT;
UPDATE orden_mantenimiento o
SET id_equipo = e.id_equipo
FROM equipo e
WHERE e.codigo = o.codigo_equipo;
ALTER TABLE orden_mantenimiento ALTER COLUMN id_equipo SET NOT NULL;
ALTER TABLE orden_mantenimiento
    ADD CONSTRAINT fk_orden_equipo
    FOREIGN KEY (id_equipo, codigo_equipo)
    REFERENCES equipo (id_equipo, codigo)
    ON UPDATE CASCADE ON DELETE RESTRICT;
CREATE INDEX idx_orden_id_equipo ON orden_mantenimiento(id_equipo);

DO $$
BEGIN
    IF to_regclass('public.registro_carbono') IS NOT NULL THEN
        EXECUTE 'ALTER TABLE registro_carbono ADD COLUMN id_equipo BIGINT';
        EXECUTE 'UPDATE registro_carbono r SET id_equipo = e.id_equipo '
             || 'FROM equipo e WHERE e.codigo = r.codigo_equipo';
        EXECUTE 'ALTER TABLE registro_carbono ALTER COLUMN id_equipo SET NOT NULL';
        EXECUTE 'ALTER TABLE registro_carbono ADD CONSTRAINT fk_registro_carbono_equipo '
             || 'FOREIGN KEY (id_equipo, codigo_equipo) '
             || 'REFERENCES equipo (id_equipo, codigo) '
             || 'ON UPDATE CASCADE ON DELETE RESTRICT';
        EXECUTE 'CREATE INDEX idx_registro_carbono_id_equipo ON registro_carbono(id_equipo)';
    END IF;
END $$;

CREATE TABLE accion_historial (
    id_accion BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tipo VARCHAR(30) NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    snapshot JSONB NOT NULL,
    deshecha BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_accion_historial PRIMARY KEY (id_accion),
    CONSTRAINT ck_accion_historial_tipo
        CHECK (tipo IN ('CREAR', 'MODIFICAR', 'CANCELAR', 'CERRAR', 'BAJA_EQUIPO'))
);

CREATE INDEX idx_accion_historial_lifo
    ON accion_historial(id_accion DESC) WHERE NOT deshecha;

COMMIT;
