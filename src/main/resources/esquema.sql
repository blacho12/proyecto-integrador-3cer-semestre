-- Esquema de la base de datos PostgreSQL (fuente de verdad para una base nueva).
-- Aplicar una sola vez:
--   psql -U postgres -d mantenimiento -f esquema.sql
-- Después aplicar esquema_carbono.sql para habilitar las tablas de huella de carbono.
-- Las columnas energeticas de equipo ya existen aqui para que el backend pueda
-- arrancar con este archivo aunque carbono no este habilitado.

CREATE TABLE area (
    id_area INTEGER GENERATED ALWAYS AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(250),

    CONSTRAINT pk_area PRIMARY KEY (id_area),
    CONSTRAINT uq_area_nombre UNIQUE (nombre)
);

CREATE TABLE equipo (
    id_equipo BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(30) NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    id_area INTEGER NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    consumo_normal_kwh NUMERIC(10,2) NOT NULL DEFAULT 0,
    porcentaje_extra NUMERIC(5,2) NOT NULL DEFAULT 0,

    CONSTRAINT pk_equipo PRIMARY KEY (id_equipo),
    CONSTRAINT uq_equipo_codigo UNIQUE (codigo),
    CONSTRAINT uq_equipo_id_codigo UNIQUE (id_equipo, codigo),
    CONSTRAINT ck_equipo_consumo_normal CHECK (consumo_normal_kwh >= 0),
    CONSTRAINT ck_equipo_porcentaje_extra CHECK (porcentaje_extra >= 0),
    CONSTRAINT ck_equipo_porcentaje_extra_max CHECK (porcentaje_extra <= 100),
    CONSTRAINT fk_equipo_area
        FOREIGN KEY (id_area)
        REFERENCES area(id_area)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE orden_mantenimiento (
    id_orden BIGINT GENERATED ALWAYS AS IDENTITY,
    consecutivo BIGINT GENERATED ALWAYS AS IDENTITY,
    id_equipo BIGINT NOT NULL,
    codigo_equipo VARCHAR(30) NOT NULL,
    tipo VARCHAR(15) NOT NULL,
    descripcion TEXT NOT NULL,
    impacto_produccion SMALLINT NOT NULL,
    riesgo_seguridad SMALLINT NOT NULL,
    hay_respaldo BOOLEAN NOT NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE',
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_cierre TIMESTAMP NULL,

    CONSTRAINT pk_orden_mantenimiento
        PRIMARY KEY (id_orden),

    CONSTRAINT uq_orden_consecutivo
        UNIQUE (consecutivo),

    CONSTRAINT fk_orden_equipo
        FOREIGN KEY (id_equipo, codigo_equipo)
        REFERENCES equipo(id_equipo, codigo)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_orden_tipo
        CHECK (tipo IN ('PREVENTIVO', 'CORRECTIVO')),

    CONSTRAINT ck_orden_impacto
        CHECK (impacto_produccion BETWEEN 1 AND 3),

    CONSTRAINT ck_orden_riesgo
        CHECK (riesgo_seguridad BETWEEN 1 AND 3),

    CONSTRAINT ck_orden_estado
        CHECK (estado IN ('PENDIENTE', 'CERRADA', 'CANCELADA')),

    CONSTRAINT ck_orden_fechas
        CHECK (
            (estado = 'PENDIENTE' AND fecha_cierre IS NULL)
            OR
            (estado IN ('CERRADA', 'CANCELADA')
             AND fecha_cierre IS NOT NULL)
        )
);

CREATE INDEX idx_orden_estado
    ON orden_mantenimiento(estado);

CREATE INDEX idx_orden_equipo
    ON orden_mantenimiento(codigo_equipo);

CREATE INDEX idx_orden_id_equipo
    ON orden_mantenimiento(id_equipo);

CREATE INDEX idx_orden_prioridad
    ON orden_mantenimiento(estado, consecutivo);

CREATE TABLE accion_historial (
    id_accion BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tipo VARCHAR(30) NOT NULL,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    snapshot JSONB NOT NULL,
    deshecha BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_accion_historial PRIMARY KEY (id_accion),
    CONSTRAINT ck_accion_historial_tipo
        CHECK (tipo IN ('CREAR', 'MODIFICAR', 'CANCELAR', 'CERRAR', 'BAJA_EQUIPO'))
);

CREATE INDEX idx_accion_historial_lifo
    ON accion_historial(id_accion DESC) WHERE NOT deshecha;
